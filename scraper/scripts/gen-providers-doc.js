#!/usr/bin/env node
/**
 * Generate PROVIDERS.md from the provider registry.
 *
 * The matrix is generated rather than hand-written so it cannot drift from the
 * code: `npm run doc:providers` rewrites it, and a test fails if the committed
 * file is stale. Run it after adding a provider or changing a `types` export.
 *
 * Usage:
 *   node scripts/gen-providers-doc.js           write PROVIDERS.md
 *   node scripts/gen-providers-doc.js --check    exit 1 if it would change
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..');
const OUT  = join(REPO, 'PROVIDERS.md');

const TYPES = ['movie', 'series', 'anime'];

export async function render() {
  // Imported with no SCRAPER_DISABLED_PROVIDERS so the document describes the
  // project, not whichever host happened to generate it.
  delete process.env.SCRAPER_DISABLED_PROVIDERS;
  const { PROVIDER_DOMAINS } = await import('../lib/domainRotation.js');

  const dir = join(HERE, '..', 'providers');
  const files = readdirSync(dir)
    .filter(f => f.endsWith('.js') && f !== 'index.js' && !f.startsWith('_'))
    .sort();

  const rows = [];
  for (const file of files) {
    const mod = await import(join(dir, file));
    rows.push({
      id:       mod.id,
      name:     mod.name,
      types:    mod.types,
      file,
      mirrors:  PROVIDER_DOMAINS[mod.id]?.length ?? 0,
    });
  }
  rows.sort((a, b) => a.id.localeCompare(b.id));

  const mismatched = rows.filter(r => r.file !== `${r.id}.js`);

  const lines = [];
  lines.push('# Providers');
  lines.push('');
  lines.push('<!-- Generated by scraper/scripts/gen-providers-doc.js. Do not edit by hand. -->');
  lines.push('');
  lines.push(`${rows.length} providers. The **id** column is what you pass to \`?providers=\`,`);
  lines.push('and an unknown id is rejected with a 400 that lists the known ones.');
  lines.push('A host can switch any of them off with `SCRAPER_DISABLED_PROVIDERS`,');
  lines.push('which is reported separately from an unknown id.');
  lines.push('');
  lines.push('| id | name | movie | series | anime | mirrors | module |');
  lines.push('| --- | --- | :-: | :-: | :-: | :-: | --- |');
  for (const r of rows) {
    const cells = TYPES.map(t => (r.types.includes(t) ? 'yes' : '-'));
    const mirrors = r.mirrors > 1 ? String(r.mirrors) : '-';
    lines.push(`| \`${r.id}\` | ${r.name} | ${cells.join(' | ')} | ${mirrors} | \`${r.file}\` |`);
  }
  lines.push('');
  lines.push('**mirrors** is how many domains the provider rotates through when one is');
  lines.push('blocked or down. A dash means it has a single fixed host.');
  lines.push('');

  if (mismatched.length) {
    lines.push('## Ids that do not match their filename');
    lines.push('');
    lines.push('The id is the site\'s name, the module is named for its implementation, and');
    lines.push('these two disagree. Pass the **id**, never the filename:');
    lines.push('');
    for (const r of mismatched) {
      lines.push(`- \`${r.file}\` registers as **\`${r.id}\`**, not \`${r.file.replace(/\.js$/, '')}\`.`);
    }
    lines.push('');
  }

  lines.push('## Adding one');
  lines.push('');
  lines.push('Copy `scraper/providers/_template.js`, then register the module in');
  lines.push('`scraper/providers/index.js` and add the id to `TorrentProvider` in');
  lines.push('`addon/lib/types.js` plus a `PublicProviderAliases` entry in');
  lines.push('`addon/lib/configuration.js`, or it will not be selectable. Declare `types`');
  lines.push('to match what `scrape()` actually serves. `scraper/test/provider-contract.test.js`');
  lines.push('checks all of that. Regenerate this file with `npm run doc:providers`.');
  lines.push('');
  return lines.join('\n');
}

// Only when run as a command. The drift test imports `render()`, and importing
// a module must never rewrite the file it is being used to check.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const expected = await render();

  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch { /* missing counts as stale */ }
    if (current !== expected) {
      console.error('PROVIDERS.md is out of date. Run: npm run doc:providers');
      process.exit(1);
    }
    console.log('PROVIDERS.md is up to date.');
  } else {
    writeFileSync(OUT, expected);
    console.log(`Wrote ${OUT}`);
  }
}
